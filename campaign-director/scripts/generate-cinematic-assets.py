"""Original lightweight technical overlays. Deterministic, no external art or runtime dependency."""
from PIL import Image, ImageDraw, ImageFilter
from pathlib import Path
import math, random, subprocess, tempfile
root=Path(__file__).resolve().parents[1]/'dist/assets/cinematic';root.mkdir(parents=True,exist_ok=True)
rng=random.Random(17)
for name in ['fog','smoke','dust','warm-beam','warm-flicker','unstable-light','blood-floor','shadow']:
 im=Image.new('RGBA',(512,288));d=ImageDraw.Draw(im)
 if name in ['fog','smoke']:
  for _ in range(28):
   x=rng.randrange(-100,512);y=rng.randrange(100,320) if name=='fog' else rng.randrange(0,288)
   d.ellipse((x,y,x+rng.randrange(90,230),y+rng.randrange(20,85)),fill=(170,159,145,25))
  im=im.filter(ImageFilter.GaussianBlur(22))
 elif name=='dust':
  for _ in range(100):
   x,y=rng.randrange(512),rng.randrange(288);d.ellipse((x,y,x+2,y+2),fill=(255,217,142,rng.randrange(30,140)))
 elif name=='blood-floor':
  for _ in range(22):
   x,y=rng.randrange(150,355),rng.randrange(130,170);d.ellipse((x,y,x+rng.randrange(5,80),y+rng.randrange(3,14)),fill=(62,5,15,rng.randrange(90,190)))
  im=im.filter(ImageFilter.GaussianBlur(.5))
 else:
  px=im.load()
  for y in range(288):
   for x in range(512):
    r=math.hypot((x-256)/256,(y-144)/144)
    if name=='shadow':color=(9,4,14);alpha=max(0,min(1,(r-.35)/.8))*.85
    elif name=='warm-beam':color=(255,217,124);alpha=max(0,1-abs(x-256)/(20+y*.55))*max(0,1-y/320)*.4
    else:color=(255,203,112);alpha=max(0,1-r)*.38
    px[x,y]=(*color,round(alpha*255))
 im.save(root/(name+'.png'))
# Two short reproducible WebMs: opaque living background fixture and transparent fog.
with tempfile.TemporaryDirectory() as temp:
 for n in range(48):
  base=Image.open(root/'fog.png');base=base.transform(base.size,Image.Transform.AFFINE,(1,0,math.sin(n/48*math.tau)*12,0,1,math.cos(n/48*math.tau)*3))
  base.save(Path(temp)/f'{n:03}.png')
 subprocess.run(['ffmpeg','-y','-loglevel','error','-framerate','12','-i',str(Path(temp)/'%03d.png'),'-c:v','libvpx-vp9','-pix_fmt','yuva420p','-auto-alt-ref','0','-b:v','0','-crf','33',str(root/'fog-loop.webm')],check=True)

# The corrected theater art is an input asset, not generated by this script.
if (root/'theater-corrected.png').exists():
 subprocess.run(['ffmpeg','-y','-loglevel','error','-loop','1','-i',str(root/'theater-corrected.png'),'-t','4','-r','12','-vf',"scale=640:360,eq=brightness=0.025*sin(2*PI*t/4):eval=frame",'-an','-c:v','libvpx-vp9','-pix_fmt','yuv420p','-b:v','0','-crf','36',str(root/'theater-living.webm')],check=True)
